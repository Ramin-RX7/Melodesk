// CHANGELOG.md helpers (Keep a Changelog 1.1.0) shared by the release script and CI.
//
//   node scripts/changelog.mjs notes <version>  print the section for <version> (release notes)
//   node scripts/changelog.mjs verify           validate the file

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CHANGELOG_PATH = path.join(ROOT, "CHANGELOG.md");

const SEMVER = /^\d+\.\d+\.\d+$/;
const SECTION_HEADING = /^## \[([^\]]+)\](?: - (\d{4}-\d{2}-\d{2}))?\s*$/;
const LINK_DEFINITION = /^\[[^\]]+\]: \S+\s*$/;

export function repoUrl() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const url = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  if (!url) throw new Error('package.json has no "repository" url');
  return url.replace(/^git\+/, "").replace(/\.git$/, "");
}

export function readChangelog() {
  return fs.readFileSync(CHANGELOG_PATH, "utf8").replace(/\r\n/g, "\n");
}

export function writeChangelog(text) {
  fs.writeFileSync(CHANGELOG_PATH, text);
}

// { header, sections: [{ name, date, body }] }. Link definitions are dropped and
// regenerated by serialize(), so they always match the section list.
export function parse(text) {
  const lines = text.split("\n").filter((line) => !LINK_DEFINITION.test(line));
  const sections = [];
  const header = [];
  let current = null;

  for (const line of lines) {
    const match = line.match(SECTION_HEADING);
    if (match) {
      current = { name: match[1], date: match[2] ?? null, body: [] };
      sections.push(current);
    } else if (current) {
      current.body.push(line);
    } else {
      header.push(line);
    }
  }

  return {
    header: header.join("\n").trim(),
    sections: sections.map((s) => ({ ...s, body: s.body.join("\n").trim() })),
  };
}

export function serialize({ header, sections }) {
  const repo = repoUrl();
  const versions = sections.filter((s) => s.name !== "Unreleased").map((s) => s.name);

  const blocks = sections.map((s) => {
    const heading = s.date ? `## [${s.name}] - ${s.date}` : `## [${s.name}]`;
    return s.body ? `${heading}\n\n${s.body}` : heading;
  });

  const links = sections.map((s) => {
    if (s.name === "Unreleased") {
      return versions.length
        ? `[Unreleased]: ${repo}/compare/v${versions[0]}...HEAD`
        : `[Unreleased]: ${repo}/commits/HEAD`;
    }
    const previous = versions[versions.indexOf(s.name) + 1];
    return previous
      ? `[${s.name}]: ${repo}/compare/v${previous}...v${s.name}`
      : `[${s.name}]: ${repo}/releases/tag/v${s.name}`;
  });

  return `${header}\n\n${blocks.join("\n\n")}\n\n${links.join("\n")}\n`;
}

export function hasEntries(body) {
  return /^- \S/m.test(body ?? "");
}

export function findSection(changelog, name) {
  return changelog.sections.find((s) => s.name === name);
}

// Moves the Unreleased entries into a new "## [version] - date" section.
export function release(changelog, version, date) {
  const unreleased = findSection(changelog, "Unreleased");
  const released = { name: version, date, body: unreleased.body };
  const rest = changelog.sections.filter((s) => s.name !== "Unreleased");
  return {
    header: changelog.header,
    sections: [{ name: "Unreleased", date: null, body: "" }, released, ...rest],
  };
}

export function validate(changelog) {
  const errors = [];
  const [first, ...versions] = changelog.sections;

  if (!first || first.name !== "Unreleased") {
    errors.push('The first section must be "## [Unreleased]".');
  }
  const seen = new Set();
  for (const s of versions) {
    if (!SEMVER.test(s.name)) errors.push(`"## [${s.name}]" is not a MAJOR.MINOR.PATCH version.`);
    if (!s.date)
      errors.push(`"## [${s.name}]" needs a release date: "## [${s.name}] - YYYY-MM-DD".`);
    if (seen.has(s.name)) errors.push(`Version ${s.name} appears more than once.`);
    if (!hasEntries(s.body)) errors.push(`Version ${s.name} has no entries.`);
    seen.add(s.name);
  }
  for (let i = 1; i < versions.length; i++) {
    if (compareVersions(versions[i - 1].name, versions[i].name) <= 0) {
      errors.push(
        `Versions must be newest first: ${versions[i - 1].name} is listed above ${versions[i].name}.`,
      );
    }
  }
  return errors;
}

export function compareVersions(a, b) {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return pa[i] - pb[i];
  return 0;
}

function fail(messages) {
  for (const m of messages) console.error(`✖ ${m}`);
  process.exit(1);
}

function main([command, ...args]) {
  if (command === "notes") {
    const [version] = args;
    if (!version) fail(["Usage: node scripts/changelog.mjs notes <version>"]);
    const section = findSection(parse(readChangelog()), version.replace(/^v/, ""));
    if (!section || !hasEntries(section.body)) {
      fail([`CHANGELOG.md has no entries for version ${version}.`]);
    }
    process.stdout.write(`${section.body}\n`);
    return;
  }

  if (command === "verify") {
    const errors = validate(parse(readChangelog()));
    if (errors.length) fail(errors);
    console.log("✔ CHANGELOG.md is valid");
    return;
  }

  fail(["Usage: node scripts/changelog.mjs <notes <version> | verify>"]);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
